"""Phase 8 tables, figures and the pre-registered 'real effect' rule (see PHASES.md and configs/sweep.yaml).

Reads results/ft_sw_<setting>_s<seed>.json (only runs with a .done marker), results/curves/*, results/b0_*.json.
Writes results/SWEEP.md, results/figures/sweep_<group>.png and, with --update-readme, the block between the SWEEP markers in README.md.

Baseline for every difference is the explicit baseline replicate sw_lr_1.2e-4 (same code path, same seeds, so differences are paired by seed).
A difference is called REAL only if the mean over 3 seeds is at least 0.01 in absolute value and has the same sign in all 3 seeds; anything
else is NOISE; with fewer than 3 seeds it is PENDING. Cells are person mAP50-95, mean +/- sample standard deviation over the seeds present.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import sweep_plan  # noqa: E402

R = ROOT / "results"
FIG = R / "figures"
START, END = "<!-- SWEEP:START (generated by scripts/make_sweep_tables.py) -->", "<!-- SWEEP:END -->"
BASE = "lr_1.2e-4"
SETLABEL = {"clean_bench1k": "clean COCO", "low_light_s3": "low light s3 (synth.)", "rain_s3": "rain s3 (synth.)", "occ_f50": "50 % hidden (synth.)",
            "exdark_all": "ExDark (real)", "dawn_fog": "DAWN fog (real)", "bdd_clear_day": "BDD day (real)", "bdd_night_clear": "BDD night (real)"}
# group -> ordered (level label, setting name, is_baseline); baseline levels that are not their own setting point at the replicate
GROUPS = {
    "lr": ("Learning rate (AdamW)", [("2e-5", "lr_2e-5"), ("6e-5", "lr_6e-5"), ("1.2e-4", BASE), ("3e-4", "lr_3e-4"), ("1e-3", "lr_1e-3")], "1.2e-4"),
    "schedule": ("Learning-rate schedule", [("linear", BASE), ("cosine", "cos_1.2e-4")], "linear"),
    "epochs": ("Epochs", [("5", "ep_5"), ("10", BASE), ("30", "ep_30")], "10"),
    "data": ("Training images", [("2k", "n_2k"), ("5k", "n_5k"), ("9.8k", BASE), ("30k", "n_30k")], "9.8k"),
    "freeze": ("Frozen layers", [("0", BASE), ("10", "frz_10"), ("22", "frz_22")], "0"),
    "model": ("Starting model", [("yolo11n", BASE), ("yolo11s", "m_11s"), ("yolo26n", "m_26n")], "yolo11n"),
}
# colour-blind-checked categorical slots 1, 2, 3, 5 (validated with the dataviz skill's validator; secondary encoding = marker shape + direct label + table)
FIG_SETS = [("clean_bench1k", "#2a78d6", "o"), ("low_light_s3", "#eb6834", "s"), ("exdark_all", "#1baf7a", "^"), ("bdd_night_clear", "#e87ba4", "D")]
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"


def ap(sets: dict, s: str) -> float:
    return sets[s]["ci"]["per_class"]["person"]["ap"]


def load_runs() -> dict[str, dict[int, dict]]:
    runs: dict[str, dict[int, dict]] = {}
    for p in sorted(R.glob("ft_sw_*_s*.json")):
        m = re.match(r"ft_sw_(.+)_s(\d+)\.json$", p.name)
        if m and (R / (p.stem + ".done")).exists():
            runs.setdefault(m.group(1), {})[int(m.group(2))] = json.loads(p.read_text(encoding="utf-8"))["sets"]
    return runs


def curve_stat(setting: str, seed: int) -> tuple[float | None, float | None]:
    """(last-epoch train-validation mAP50-95, training minutes) for one run, if the files exist."""
    name = f"sw_{setting}_s{seed}"
    last, mins = None, None
    c = R / "curves" / f"{name}.csv"
    if c.exists():
        rows = list(csv.DictReader(c.open(encoding="utf-8")))
        if rows:
            key = next(k for k in rows[-1] if k.strip().startswith("metrics/mAP50-95"))
            last = float(rows[-1][key])
    t = R / "curves" / f"{name}.train_seconds"
    if t.exists():
        mins = float(t.read_text().strip()) / 60.0
    return last, mins


def stats(runs, setting: str, key: str):
    seeds = sorted(runs.get(setting, {}))
    v = [ap(runs[setting][s], key) for s in seeds if key in runs[setting][s]]
    return v, seeds


def cell(v: list[float]) -> str:
    if not v:
        return "pending"
    return f"{v[0]:.3f} (n=1)" if len(v) == 1 else f"{np.mean(v):.3f} ± {np.std(v, ddof=1):.3f} (n={len(v)})"


def verdict(runs, setting: str, key: str) -> str:
    """Paired by seed against the baseline replicate."""
    if setting == BASE:
        return "baseline"
    a, sa = stats(runs, setting, key)
    b, sb = stats(runs, BASE, key)
    seeds = sorted(set(runs.get(setting, {})) & set(runs.get(BASE, {})))
    d = [ap(runs[setting][s], key) - ap(runs[BASE][s], key) for s in seeds]
    if not d:
        return "pending"
    mean = float(np.mean(d))
    if len(d) < 3:
        return f"{mean:+.3f} (pending, n={len(d)})"
    real = abs(mean) >= 0.01 and (all(x > 0 for x in d) or all(x < 0 for x in d))
    return f"{mean:+.3f} {'**REAL**' if real else 'noise'}"


def figure(group: str, runs, b0) -> Path | None:
    title, levels, base_level = GROUPS[group]
    avail = [(lv, st) for lv, st in levels if st in runs]
    if len(avail) < 2:
        return None
    fig, ax = plt.subplots(figsize=(7.2, 4.2), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    x = np.arange(len(avail))
    for key, colour, marker in FIG_SETS:
        means, errs = [], []
        for lv, st in avail:
            v, _ = stats(runs, st, key)
            means.append(np.mean(v) if v else np.nan)
            errs.append(np.std(v, ddof=1) if len(v) > 1 else 0.0)
        ax.errorbar(x, means, yerr=errs, color=colour, marker=marker, markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.5,
                    linewidth=2, capsize=3, elinewidth=1.2, zorder=3, label=SETLABEL[key])
        ax.axhline(ap(b0, key), color=colour, linewidth=1, linestyle=(0, (4, 3)), alpha=0.7, zorder=1)    # zero-shot yolo11n, same colour
        last = means[-1] if not np.isnan(means[-1]) else means[-2]
        ax.annotate(SETLABEL[key].replace(" (synth.)", "").replace(" (real)", ""), (x[-1], last), xytext=(8, 0), textcoords="offset points",
                    color=INK, fontsize=8, va="center")
    ax.set_xticks(x)
    ax.set_xticklabels([lv + ("\n(baseline)" if lv == base_level else "") for lv, _ in avail], fontsize=9, color=INK2)
    ax.set_xlim(-0.3, len(avail) - 1 + 1.1)
    ax.set_ylabel("person mAP50-95", color=INK2, fontsize=9)
    ax.set_title(f"{title}: mean ± std over seeds; dashed = zero-shot yolo11n", color=INK, fontsize=10, loc="left")
    ax.legend(frameon=False, fontsize=8, loc="upper left", ncol=2, labelcolor=INK2)
    ax.grid(axis="y", color=GRID, linewidth=0.8, zorder=0)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=9)
    FIG.mkdir(parents=True, exist_ok=True)
    out = FIG / f"sweep_{group}.png"
    fig.tight_layout()
    fig.savefig(out, facecolor=SURFACE)
    plt.close(fig)
    return out


def build() -> tuple[str, list[Path]]:
    runs = load_runs()
    cfg = sweep_plan.load()
    sets = cfg["eval_sets"]
    b0 = {m: json.loads((R / f"b0_{m}.json").read_text(encoding="utf-8"))["sets"] for m in ("yolo11n", "yolo11s", "yolo26n")}
    n_done = {k: len(v) for k, v in runs.items()}
    out = [f"Baseline: A1 recipe on yolo11n (explicit AdamW lr 0.000119, momentum 0.9, 10 epochs, 9,831 images, nothing frozen). Seeds finished so far per setting: "
           f"{min(n_done.values()) if n_done else 0} to {max(n_done.values()) if n_done else 0} of 3. Cells are person mAP50-95, mean ± sample std over the seeds present. "
           "**Effect** columns are the mean paired difference to the baseline: **REAL** = at least 0.01 in absolute value and the same sign in all 3 seeds; "
           "otherwise noise (or pending until 3 seeds exist). Zero-shot yolo11n for reference: "
           + ", ".join(f"{SETLABEL[s]} {ap(b0['yolo11n'], s):.3f}" for s in sets) + ".\n"]
    figs: list[Path] = []
    for g, (title, levels, base_level) in GROUPS.items():
        out.append(f"#### {title}\n")
        out.append("| Level | " + " | ".join(SETLABEL[s] for s in sets) + " | training time | train-val mAP50-95 (last epoch) |")
        out.append("|---|" + "---|" * (len(sets) + 2))
        eff = ["| Level | " + " | ".join(SETLABEL[s] for s in sets) + " |", "|---|" + "---|" * len(sets)]
        for lv, st in levels:
            if st not in runs:
                out.append(f"| {lv}{' (baseline)' if lv == base_level else ''} | " + " | ".join("pending" for _ in sets) + " | pending | pending |")
                continue
            cs = [curve_stat(st, s) for s in sorted(runs[st])]
            mins = [c[1] for c in cs if c[1] is not None]
            lasts = [c[0] for c in cs if c[0] is not None]
            out.append(f"| {lv}{' (baseline)' if lv == base_level else ''} | " + " | ".join(cell(stats(runs, st, s)[0]) for s in sets)
                       + f" | {np.mean(mins):.0f} min | {np.mean(lasts):.3f} |" if mins and lasts else
                       f"| {lv} | " + " | ".join(cell(stats(runs, st, s)[0]) for s in sets) + " | n/a | n/a |")
            eff.append(f"| {lv}{' (baseline)' if lv == base_level else ''} | " + " | ".join(verdict(runs, st, s) for s in sets) + " |")
        out.append("")
        out.append("Effect against the baseline:\n")
        out += eff
        out.append("")
        if g == "model":
            out.append("Each starting model against **its own** zero-shot score (person mAP50-95, mean over seeds minus zero-shot):\n")
            out.append("| Model | " + " | ".join(SETLABEL[s] for s in sets) + " |")
            out.append("|---|" + "---|" * len(sets))
            for lv, st, m in (("yolo11n", BASE, "yolo11n"), ("yolo11s", "m_11s", "yolo11s"), ("yolo26n", "m_26n", "yolo26n")):
                if st in runs:
                    out.append(f"| {lv} | " + " | ".join(f"{np.mean(stats(runs, st, s)[0]) - ap(b0[m], s):+.3f}" if stats(runs, st, s)[0] else "pending" for s in sets) + " |")
            out.append("")
        f = figure(g, runs, b0["yolo11n"])
        if f:
            figs.append(f)
            out.append(f"![{title}](results/figures/{f.name})\n")
    return "\n".join(out) + "\n", figs


def main() -> None:
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--update-readme", action="store_true")
    args = ap_.parse_args()
    md, _ = build()
    (R / "SWEEP.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text:
        raise SystemExit("README has no SWEEP markers")
    block = f"{START}\n{md}{END}"
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S), encoding="utf-8")
    print("README sweep block updated")


if __name__ == "__main__":
    main()
