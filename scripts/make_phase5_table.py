"""Phase 5 diagnosis table: the recipe experiments (D0-D3) next to zero-shot (B0) and the original clean control (B1) and A1, seed 0.

Writes results/PHASE5.md and, with --update-readme, the block between the PHASE5 markers in README.md.
Every cell is person mAP50-95 with its 95 % bootstrap interval; every run is a single seed (n=1).
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
START, END = "<!-- PHASE5:START (generated by scripts/make_phase5_table.py) -->", "<!-- PHASE5:END -->"
SETS = [("clean_bench1k", "clean COCO"), ("low_light_s3", "low light s3 (synth.)"), ("rain_s3", "rain s3 (synth.)"),
        ("exdark_all", "ExDark (real)"), ("dawn_fog", "DAWN fog (real)"), ("bdd_clear_day", "BDD clear day (real)")]
RUNS = [("B0 zero-shot", "b0_yolo11n.json", "pretrained, nothing trained"),
        ("D0 lr ~0, 3 epochs", "ft_D0_null_lr.json", "training path with essentially no learning"),
        ("D3 lr ~0, no augmentation", "ft_D3_null_plain.json", "same, and no mosaic/colour/geometry augmentation"),
        ("D5 lr ~0, batch-norm locked", "ft_D5_null_lockbn.json", "same as D0 but every BatchNorm layer kept at the pretrained statistics"),
        ("D1 lr 2e-5", "ft_D1_lr2e-5.json", "AdamW at 1/6 of the automatic rate"),
        ("D2 frozen backbone", "ft_D2_freeze_backbone.json", "first 10 layers frozen"),
        ("D4 original recipe, batch-norm locked", "ft_D4_lockbn.json", "original clean-control recipe with every BatchNorm layer locked"),
        ("B1 original (seed 0)", "ft_B1_yolo11n_s0.json", "original clean-control recipe"),
        ("A1 original (seed 0)", "ft_A1_yolo11n_s0.json", "original recipe + condition-aware augmentation")]


def build() -> str:
    out = ["Person mAP50-95 with 95 % bootstrap intervals; every run is one seed (n=1), so differences below about 0.02 are within noise "
           "(seed-to-seed standard deviation in the 3-seed runs was 0.003 to 0.024 depending on the set).\n",
           "| Run | What it is | " + " | ".join(label for _, label in SETS) + " |", "|---|---|" + "---|" * len(SETS)]
    for label, f, note in RUNS:
        p = R / f
        if not p.exists():
            continue
        d = json.loads(p.read_text(encoding="utf-8"))["sets"]
        cells = []
        for key, _ in SETS:
            pc = d[key]["ci"]["per_class"]["person"]
            cells.append(f"{pc['ap']:.3f} [{pc['lo']:.3f}, {pc['hi']:.3f}]")
        out.append(f"| {label} | {note} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update-readme", action="store_true")
    args = ap.parse_args()
    md = build()
    (R / "PHASE5.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text:
        raise SystemExit("README has no PHASE5 markers")
    block = f"{START}\n{md}{END}"
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S), encoding="utf-8")
    print("README phase 5 block updated")


if __name__ == "__main__":
    main()
