"""Tables comparing B0 (zero-shot), B1 (clean fine-tune control), A1 (+ condition-aware augmentation) and A2 (+ BDD100K adverse data).

Reads results/b0_<base>.json and results/ft_<variant>_<base>_s<seed>.json; writes results/FINETUNE_TABLES.md and, with
--update-readme, the block between the FINETUNE markers in README.md.

How to read the numbers
  * Each variant cell is the mean +/- sample standard deviation of person mAP50-95 over the seeds that exist (n is shown;
    with n=1 there is no spread and the cell is NOT a statistically supported claim).
  * "A1 - B1" isolates condition-aware augmentation (same data, same everything else). "A2 - A1" adds BDD100K adverse
    images: it is CONFOUNDED with extra data. Differences are the mean of per-seed differences (seed i of A against seed i of B).
  * SYNTHETIC rows are in-distribution for A1/A2 (training and test degradations share one generator): optimistic.
    REAL rows (ExDark, DAWN, BDD100K) are the honest test of transfer. BDD100K val shares its source with the A2 training
    images (BDD train), so A2 gains on BDD rows are in-domain too; ExDark and DAWN are never trained on.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
VARIANTS = ["B1", "A1", "A2"]
START, END = "<!-- FINETUNE:START (generated by scripts/make_finetune_tables.py) -->", "<!-- FINETUNE:END -->"
ROWS = [("clean_bench1k", "clean (COCO val sample)"), ("low_light_s2", "low light s2"), ("low_light_s3", "low light s3"),
        ("fog_s3", "fog s3"), ("rain_s3", "rain s3"), ("snow_s3", "snow s3"), ("motion_blur_s2", "motion blur s2"),
        ("motion_blur_s3", "motion blur s3"), ("gaussian_noise_s3", "noise s3"),
        ("exdark_all", "ExDark low light"), ("dawn_fog", "DAWN fog (117 persons)"), ("dawn_rain", "DAWN rain (28 persons)"),
        ("dawn_snow", "DAWN snow (158 persons)"), ("bdd_clear_day", "BDD clear day"), ("bdd_night_clear", "BDD clear night"),
        ("bdd_rainy_day", "BDD rainy day"), ("bdd_snowy_day", "BDD snowy day")]


def ap(r: dict) -> float:
    return r["ci"]["per_class"]["person"]["ap"]


def load_runs(base: str) -> dict[str, dict[int, dict]]:
    runs: dict[str, dict[int, dict]] = {v: {} for v in VARIANTS}
    for v in VARIANTS:
        for p in sorted(RESULTS.glob(f"ft_{v}_{base}_s*.json")):
            m = re.search(r"_s(\d+)\.json$", p.name)
            if m and (RESULTS / (p.stem + ".done")).exists():          # only fully evaluated runs
                runs[v][int(m.group(1))] = json.loads(p.read_text(encoding="utf-8"))["sets"]
    return runs


def cell(vals: list[float]) -> str:
    if not vals:
        return "pending"
    if len(vals) == 1:
        return f"{vals[0]:.3f} (n=1)"
    return f"{np.mean(vals):.3f} ± {np.std(vals, ddof=1):.3f} (n={len(vals)})"


def diff(runs, a: str, b: str, key: str, fn=ap) -> str:
    seeds = sorted(set(runs[a]) & set(runs[b]))
    d = [fn(runs[a][s][key]) - fn(runs[b][s][key]) for s in seeds if key in runs[a][s] and key in runs[b][s]]
    if not d:
        return "-"
    if len(d) == 1:
        return f"{d[0]:+.3f} (n=1)"
    return f"{np.mean(d):+.3f} ± {np.std(d, ddof=1):.3f} (n={len(d)})"


def build(base: str) -> str:
    b0p = RESULTS / f"b0_{base}.json"
    if not b0p.exists():
        return "_No baseline file._\n"
    b0 = json.loads(b0p.read_text(encoding="utf-8"))["sets"]
    runs = load_runs(base)
    n = {v: len(runs[v]) for v in VARIANTS}
    out = [f"Model: `{base}`. Seeds evaluated so far: B1 {n['B1']}, A1 {n['A1']}, A2 {n['A2']}. 10 epochs, identical settings except as described. "
           "Each cell is person mAP50-95, mean ± sample std over seeds (n shown).\n"]
    if not any(n.values()):
        out.append("_No fine-tuned model has been evaluated yet._\n")
        return "\n".join(out)
    out.append("| Test set (evidence) | B0 zero-shot | B1 clean fine-tune | A1 + condition-aware aug. | A2 + BDD adverse data | A1 - B1 | A2 - A1 (confounded) |")
    out.append("|---|---|---|---|---|---|---|")
    for key, label in ROWS:
        if key not in b0:
            continue
        ev = b0[key]["evidence"]
        vals = {v: [ap(runs[v][s][key]) for s in sorted(runs[v]) if key in runs[v][s]] for v in VARIANTS}
        out.append(f"| {label} ({ev}) | {ap(b0[key]):.3f} | {cell(vals['B1'])} | {cell(vals['A1'])} | {cell(vals['A2'])} | "
                   f"{diff(runs, 'A1', 'B1', key)} | {diff(runs, 'A2', 'A1', key)} |")
    out.append("")
    out.append("**Occlusion: person found rate (IoU >= 0.1, confidence >= 0.25)**\n")
    out.append("| Hidden | B0 | B1 | A1 | A2 |")
    out.append("|---|---|---|---|---|")
    for key, label in (("occ_clean", "0 %"), ("occ_f25", "25 %"), ("occ_f50", "50 %"), ("occ_f75", "75 %")):
        fr = lambda r: r["ci"]["found_person"]["iou0.1"]["rate"]
        row = [f"{fr(b0[key]):.3f}"]
        for v in VARIANTS:
            vals = [fr(runs[v][s][key]) for s in sorted(runs[v]) if key in runs[v][s]]
            row.append(cell(vals))
        out.append(f"| {label} | " + " | ".join(row) + " |")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--base", default="yolo11n")
    ap_.add_argument("--update-readme", action="store_true")
    args = ap_.parse_args()
    md = build(args.base)
    (RESULTS / "FINETUNE_TABLES.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text:
        sys.exit("README has no FINETUNE markers")
    block = f"{START}\n{md}{END}"
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S), encoding="utf-8")
    print("README fine-tuning block updated")


if __name__ == "__main__":
    main()
