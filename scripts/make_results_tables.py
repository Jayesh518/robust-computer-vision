"""Generate the README results tables straight from results/b0_<model>.json (no hand-copied numbers).

    .venv\\Scripts\\python scripts\\make_results_tables.py                 # print markdown
    .venv\\Scripts\\python scripts\\make_results_tables.py --update-readme # replace the block between the RESULTS markers

Every number carries its 95 % bootstrap interval where one exists. Evidence is labelled: SYNTHETIC (degraded COCO val),
REAL (ExDark, DAWN, BDD100K photographs), CLEAN (reference).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
MODELS = ["yolo11n", "yolo11s", "yolo26n"]
CONDITIONS = ["low_light", "fog", "rain", "snow", "motion_blur", "gaussian_noise"]
START, END = "<!-- RESULTS:START (generated by scripts/make_results_tables.py) -->", "<!-- RESULTS:END -->"


def load(model: str) -> dict | None:
    p = RESULTS / f"b0_{model}.json"
    return json.loads(p.read_text(encoding="utf-8"))["sets"] if p.exists() else None


def person(r: dict) -> tuple[float, float, float]:
    c = r["ci"]["per_class"]["person"]
    return c["ap"], c["lo"], c["hi"]


def fmt(r: dict | None) -> str:
    if r is None or "person" not in r["ci"]["per_class"]:
        return "n/a"
    a, lo, hi = person(r)
    return f"{a:.3f} [{lo:.3f}, {hi:.3f}]"


def fmt_found(r: dict, thr: str) -> str:
    f = r["ci"]["found_person"].get(thr)
    return "n/a" if not f or f["rate"] is None else f"{f['rate']:.3f} [{f['lo']:.3f}, {f['hi']:.3f}]"


def role_txt(r: dict, role: str) -> str:
    x = r["ci"]["roles"].get(role)
    return "n/a" if not x or x["ap"] is None else f"{x['ap']:.3f} [{x['lo']:.3f}, {x['hi']:.3f}]"


def drop_txt(r: dict) -> str:
    for k, v in r.items():
        if k.startswith("person_drop_vs_"):
            return f"{v['drop']:+.3f} [{v['lo']:+.3f}, {v['hi']:+.3f}]"
    return "-"


def n_person(r: dict) -> int:
    return r.get("objects_per_class", {}).get("person", 0)


def tables() -> str:
    data = {m: load(m) for m in MODELS}
    have = [m for m in MODELS if data[m]]
    out = []
    if not have:
        return "_No result files yet._\n"
    out.append(f"Models evaluated zero-shot: {', '.join(have)}. Intervals are 95 % bootstrap CIs (images resampled, 200 draws). "
               "Evidence labels: **synthetic** = degraded COCO val images; **real** = genuine photographs; **clean** = reference.\n")

    # 1. models, clean reference
    out.append("### Model comparison on clean images (COCO val, 1000-image sample; mAP50-95)\n")
    out.append("| Model | Person (primary) | Animals (secondary, macro) | Vehicles (context, macro) | Latency batch 1 |")
    out.append("|---|---|---|---|---|")
    lat = {}
    lp = RESULTS / "latency_models.json"
    if lp.exists():
        lat = json.loads(lp.read_text(encoding="utf-8"))
    for m in have:
        r = data[m]["clean_bench1k"]
        l = lat.get(m)
        ltxt = f"{l['p50_ms']:.1f} ms median ({l['params_m']:.1f} M params)" if l else "not measured"
        out.append(f"| {m} | {fmt(r)} | {role_txt(r, 'secondary')} | {role_txt(r, 'context')} | {ltxt} |")
    out.append("")

    # 2. synthetic degradations, every model, person, severity 3 and the drop
    out.append("### Synthetic degradation, strongest severity (s3): person mAP50-95 and drop from clean\n")
    out.append("Severities are my own settings (`configs/conditions.yaml`): compare a condition with itself across models, "
               "not one condition against another.\n")
    out.append("| Condition (synthetic) | " + " | ".join(f"{m}: s3 (drop)" for m in have) + " |")
    out.append("|---|" + "---|" * len(have))
    for cond in CONDITIONS:
        row = []
        for m in have:
            r = data[m].get(f"{cond}_s3")
            clean = data[m]["clean_bench1k"]
            row.append("n/a" if r is None else f"{person(r)[0]:.3f} ({person(r)[0] - person(clean)[0]:+.3f})")
        out.append(f"| {cond.replace('_', ' ')} | " + " | ".join(row) + " |")
    out.append("")

    # 3. full severity table for the primary model
    m0 = "yolo11n" if "yolo11n" in have else have[0]
    out.append(f"### {m0}: person mAP50-95 by condition and severity (synthetic), with CIs\n")
    out.append("| Condition | clean | s1 | s2 | s3 |")
    out.append("|---|---|---|---|---|")
    clean = data[m0]["clean_bench1k"]
    for cond in CONDITIONS:
        cells = [fmt(data[m0].get(f"{cond}_s{s}")) for s in (1, 2, 3)]
        out.append(f"| {cond.replace('_', ' ')} | {fmt(clean)} | " + " | ".join(cells) + " |")
    out.append("")

    # 4. occlusion
    out.append("### Occlusion (synthetic slab hides part of each person's box; 500 images, all persons at least 40 px)\n")
    out.append("The strict score uses the person's FULL box as ground truth, but a detector boxes what it can SEE, so it falls even when the "
               "person is found. The **found rate** (a detection of a person at confidence 0.25 or more overlapping the full box with the "
               "stated IoU) is the lenient measure for \"was a person detected there at all?\".\n")
    out.append("| Model | Hidden | mAP50-95 | mAP50 | found IoU>=0.1 | found IoU>=0.3 | found IoU>=0.5 |")
    out.append("|---|---|---|---|---|---|---|")
    for m in have:
        for key, label in (("occ_clean", "0 %"), ("occ_f25", "25 %"), ("occ_f50", "50 %"), ("occ_f75", "75 %")):
            r = data[m].get(key)
            if r:
                out.append(f"| {m} | {label} | {fmt(r)} | {r['roles']['primary']['map50']:.3f} | {fmt_found(r, 'iou0.1')} | "
                           f"{fmt_found(r, 'iou0.3')} | {fmt_found(r, 'iou0.5')} |")
    out.append("")

    # 5. real sets
    out.append("### REAL photographs (test-only): person mAP50-95, with person-box counts\n")
    out.append("BDD100K rows give the drop against the BDD **clear-daytime** reference (different images, so the interval comes from "
               "independent resampling). ExDark and DAWN have no clean reference, so no drop can be computed for them. "
               "Sets with few person boxes carry wide intervals: read the interval, not the point.\n")
    out.append("| Set (condition) | Person boxes | " + " | ".join(f"{m}" for m in have) + " | Drop vs reference (" + m0 + ") |")
    out.append("|---|---|" + "---|" * len(have) + "---|")
    real = [("exdark_all", "ExDark (low light)"), ("dawn_fog", "DAWN fog"), ("dawn_rain", "DAWN rain"), ("dawn_snow", "DAWN snow"),
            ("bdd_clear_day", "BDD clear day (reference)"), ("bdd_night_clear", "BDD clear night"), ("bdd_rainy_day", "BDD rainy day"),
            ("bdd_snowy_day", "BDD snowy day"), ("bdd_rainy_night", "BDD rainy night (vs clear night)"),
            ("bdd_snowy_night", "BDD snowy night (vs clear night)"), ("bdd_foggy_all", "BDD foggy (13 images)")]
    for key, label in real:
        base = data[m0].get(key)
        if base is None:
            continue
        out.append(f"| {label} | {n_person(base)} | " + " | ".join(fmt(data[m].get(key)) for m in have) + f" | {drop_txt(base)} |")
    out.append("")

    # 6. the other classes on real low light (the only real evidence for animals)
    out.append("### REAL low light (ExDark): the other classes, macro mAP50-95 (cat and dog are the only real-photo animal evidence)\n")
    out.append("| Model | Animals: cat, dog | Vehicles: car, bus |")
    out.append("|---|---|---|")
    for m in have:
        r = data[m].get("exdark_all")
        if r:
            out.append(f"| {m} | {role_txt(r, 'secondary')} | {role_txt(r, 'context')} |")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update-readme", action="store_true")
    args = ap.parse_args()
    md = tables()
    (RESULTS / "TABLES.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    block = f"{START}\n{md}{END}"
    if START in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        sys.exit("README has no RESULTS markers; add them where the generated tables should go")
    readme.write_text(text, encoding="utf-8")
    print("README results block updated")


if __name__ == "__main__":
    main()
