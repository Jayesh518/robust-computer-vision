"""Phase 6 (E1) tables and the pre-registered decision rule, applied as written (see PHASES.md).

Reads results/e1_yolo11n.json and results/enhancement_latency.json; writes results/E1.md and, with --update-readme,
the block between the E1 markers in README.md.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
START, END = "<!-- E1:START (generated by scripts/make_e1_table.py) -->", "<!-- E1:END -->"
DETECTOR_MS = 16.1          # yolo11n batch-1 forward pass measured in scripts/measure_latency.py
LABEL = {"clean_bench1k": "clean COCO sample", "low_light_s2": "low light s2 (synthetic)", "low_light_s3": "low light s3 (synthetic)",
         "exdark_all": "ExDark (real)", "bdd_night_clear": "BDD clear night (real)", "fog_s3": "fog s3 (synthetic)",
         "dawn_fog": "DAWN fog (real, 117 persons)", "gaussian_noise_s3": "noise s3 (synthetic)"}
METHOD = {"clahe": "CLAHE", "gamma": "adaptive gamma", "dcp": "dark-channel dehaze", "nlm": "non-local-means"}
# condition -> (synthetic set, real set or None, methods)
CONDITIONS = {"low light": ("low_light_s3", "exdark_all", ["clahe", "gamma"]), "fog": ("fog_s3", "dawn_fog", ["dcp"]),
              "noise": ("gaussian_noise_s3", None, ["nlm"])}


def fmt(g: dict) -> str:
    return f"{g['gain']:+.3f} [{g['lo']:+.3f}, {g['hi']:+.3f}]"


def helps(g: dict) -> bool:
    return g["gain"] >= 0.01 and g["lo"] > 0


def build() -> str:
    d = json.loads((R / "e1_yolo11n.json").read_text(encoding="utf-8"))["sources"]
    out = ["Zero-shot yolo11n (unchanged) on original images and on the same images after classical enhancement. Gain = enhanced minus original person mAP50-95, paired on identical images, with a 95 % bootstrap interval.\n",
           "| Source set | Method | Original | Enhanced | Gain vs original | Gain vs re-encode control | Enhancement time per image (median / p95) |", "|---|---|---|---|---|---|---|"]
    for src, rec in d.items():
        o = rec["original"]["ci"]["per_class"]["person"]["ap"]
        for m, mr in rec["methods"].items():
            e = mr["result"]["ci"]["per_class"]["person"]["ap"]
            lat = mr["latency"]
            out.append(f"| {LABEL[src]} | {METHOD[m]} | {o:.3f} | {e:.3f} | {fmt(mr['gain_vs_original'])} | {fmt(mr['gain_vs_none'])} | {lat['median_ms']:.0f} / {lat['p95_ms']:.0f} ms |")
    out.append("\n**Re-encode control** (the same images saved again without enhancement; should be near zero):\n")
    out.append("| Source set | control gain vs original |")
    out.append("|---|---|")
    ctrl_ok = True
    for src, rec in d.items():
        c = rec["none_vs_original"]
        ctrl_ok &= abs(c["gain"]) <= 0.005
        out.append(f"| {LABEL[src]} | {fmt(c)} |")
    out.append(f"\nControl check (all within 0.005 of zero): **{'passed' if ctrl_ok else 'not passed for every set; the gains vs the control column are the ones to read'}**.\n")
    out.append("**Pre-registered rule, applied as written** (a method helps on a condition if the paired gain is at least +0.01 with the interval's lower bound above 0, on the real set and on the synthetic set; harmful on clean images if the clean-sample gain is below -0.01 with the interval excluding 0):\n")
    out.append("| Condition | Method | Synthetic | Real | Clean-sample effect | Verdict |")
    out.append("|---|---|---|---|---|---|")
    for cond, (syn, real, methods) in CONDITIONS.items():
        for m in methods:
            if syn not in d or m not in d[syn]["methods"]:
                continue
            gs = d[syn]["methods"][m]["gain_vs_original"]
            gr = d[real]["methods"][m]["gain_vs_original"] if real and real in d and m in d[real]["methods"] else None
            gc = d["clean_bench1k"]["methods"][m]["gain_vs_original"]
            if gr is None:
                verdict = "synthetic-only possible" if helps(gs) else "does not help"
            elif helps(gs) and helps(gr):
                verdict = "helps"
            elif helps(gs):
                verdict = "synthetic-only"
            elif helps(gr):
                verdict = "real-only"
            else:
                verdict = "does not help"
            if cond == "fog" and gr is not None and (gr["hi"] - gr["lo"]) > 0.08 and not helps(gr):
                verdict += " (real set inconclusive: wide interval)"
            harm = gc["gain"] < -0.01 and gc["hi"] < 0
            out.append(f"| {cond} | {METHOD[m]} | {fmt(gs)} | {fmt(gr) if gr else 'no real set'} | {fmt(gc)}{' (harmful)' if harm else ''} | {verdict} |")
    out.append(f"\nLatency context: the detector forward pass is {DETECTOR_MS} ms (batch 1, GPU); the enhancement times above are CPU times at the stored image size and would add to it.\n")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--update-readme", action="store_true")
    args = ap.parse_args()
    md = build()
    (R / "E1.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text:
        raise SystemExit("README has no E1 markers")
    block = f"{START}\n{md}{END}"
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S), encoding="utf-8")
    print("README E1 block updated")


if __name__ == "__main__":
    main()
