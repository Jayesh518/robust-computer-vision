"""Phase 5d: B1L / A1L (BatchNorm locked) against zero-shot, and the pre-registered decision rule from PHASES.md applied as written.

Writes results/PHASE5D.md and, with --update-readme, the block between the PHASE5D markers in README.md.
Cells are person mAP50-95, mean ± sample standard deviation over 3 seeds.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
START, END = "<!-- PHASE5D:START (generated by scripts/make_phase5d_table.py) -->", "<!-- PHASE5D:END -->"
COLS = [("clean_bench1k", "clean COCO"), ("low_light_s3", "low light s3 (synth.)"), ("rain_s3", "rain s3 (synth.)"),
        ("motion_blur_s3", "motion blur s3 (synth.)"), ("exdark_all", "ExDark (real)"), ("dawn_fog", "DAWN fog (real)"),
        ("dawn_snow", "DAWN snow (real)"), ("bdd_clear_day", "BDD clear day (real)"), ("bdd_night_clear", "BDD clear night (real)")]
RULE_SETS = ("exdark_all", "dawn_fog", "bdd_night_clear")


def ap(d: dict, s: str) -> float:
    return d[s]["ci"]["per_class"]["person"]["ap"]


def load(f: str) -> dict:
    return json.loads((R / f).read_text(encoding="utf-8"))["sets"]


def build() -> str:
    b0 = load("b0_yolo11n.json")
    runs = {n: [load(f"ft_{n.split()[0]}_yolo11n_s{i}.json") for i in range(3)]
            for n in ("B1 original", "A1 original", "B1L locked", "A1L locked")}
    cell = lambda rs, s: f"{np.mean([ap(r, s) for r in rs]):.3f} ± {np.std([ap(r, s) for r in rs], ddof=1):.3f}"
    out = ["Person mAP50-95, mean ± sample standard deviation over 3 seeds (yolo11n, 10 epochs). B1L and A1L are B1 and A1 with every BatchNorm layer locked.\n",
           "| Run | " + " | ".join(label for _, label in COLS) + " |", "|---|" + "---|" * len(COLS),
           "| B0 zero-shot | " + " | ".join(f"{ap(b0, s):.3f}" for s, _ in COLS) + " |"]
    for n, rs in runs.items():
        out.append(f"| {n} | " + " | ".join(cell(rs, s) for s, _ in COLS) + " |")
    out.append("\n**Pre-registered rule, applied as written** (transfer supported if A1L minus zero-shot is at least +0.01 on all three of ExDark, DAWN fog and BDD clear night, and A1L beats B1L on ExDark in all 3 seeds):\n")
    out.append("| Set | A1L minus zero-shot, per seed | mean | needed |")
    out.append("|---|---|---|---|")
    A = runs["A1L locked"]
    ok = True
    for s in RULE_SETS:
        d = [ap(a, s) - ap(b0, s) for a in A]
        ok &= float(np.mean(d)) >= 0.01
        out.append(f"| {dict(COLS)[s]} | " + ", ".join(f"{x:+.3f}" for x in d) + f" | {np.mean(d):+.3f} | at least +0.010 |")
    dd = [ap(a, "exdark_all") - ap(b, "exdark_all") for a, b in zip(A, runs["B1L locked"])]
    ok &= all(x > 0 for x in dd)
    out.append(f"| ExDark, A1L minus B1L | " + ", ".join(f"{x:+.3f}" for x in dd) + f" | {np.mean(dd):+.3f} | positive in all 3 seeds |")
    out.append(f"\n**Verdict: {'transfer supported' if ok else 'transfer NOT supported'}.**\n")
    return "\n".join(out) + "\n"


def main() -> None:
    ap_ = argparse.ArgumentParser()
    ap_.add_argument("--update-readme", action="store_true")
    args = ap_.parse_args()
    md = build()
    (R / "PHASE5D.md").write_text(md, encoding="utf-8")
    if not args.update_readme:
        print(md)
        return
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text:
        raise SystemExit("README has no PHASE5D markers")
    block = f"{START}\n{md}{END}"
    readme.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S), encoding="utf-8")
    print("README phase 5d block updated")


if __name__ == "__main__":
    main()
